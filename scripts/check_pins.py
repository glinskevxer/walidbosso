#!/usr/bin/env python3
"""Every dependency is pinned, and the lock agrees with the pins.

This package pins exact versions rather than ranges. That is unusual for a
library and right for this one: it is an application, it ships in a container,
and a build that resolves differently on Tuesday from the way it resolved on
Monday is a build nobody can debug.

Three things are checked and each has bitten somewhere:

**Everything is ``==``.** A single ``>=`` in an extra is enough to make the
container non reproducible, and it will not be noticed until the day the new
version breaks.

**The constraints file matches.** ``constraints.txt`` is what CI installs
with. If it drifts from ``pyproject.toml``, CI is testing something other than
what ships.

**Nothing is pinned twice at different versions.** Two extras can both name a
package; naming it at two versions is a resolution failure waiting for the day
both extras are installed together.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONSTRAINTS = ROOT / "constraints.txt"

PIN = re.compile(r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[A-Za-z0-9.+!-]+)$")


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def declared() -> dict[str, tuple[str, str]]:
    """Every pin in pyproject, keyed by normalised name, with where it came from."""
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    groups: dict[str, list[str]] = {"dependencies": project.get("dependencies", [])}
    groups.update(project.get("optional-dependencies", {}))

    found: dict[str, tuple[str, str]] = {}
    problems: list[str] = []
    for group, requirements in groups.items():
        for requirement in requirements:
            bare = requirement.split(";")[0].strip()
            match = PIN.match(bare)
            if match is None:
                problems.append(f"{group}: {requirement!r} is not an exact pin")
                continue
            name = _normalise(match.group("name"))
            version = match.group("version")
            if name in found and found[name][0] != version:
                problems.append(
                    f"{name} is pinned at {found[name][0]} in {found[name][1]}"
                    f" and {version} in {group}"
                )
            found[name] = (version, group)
    if problems:
        raise SystemExit("\n".join(problems))
    return found


def locked() -> dict[str, str]:
    if not CONSTRAINTS.is_file():
        return {}
    found: dict[str, str] = {}
    for number, raw in enumerate(CONSTRAINTS.read_text().splitlines(), start=1):
        line = raw.split("#")[0].strip()
        if not line:
            continue
        match = PIN.match(line)
        if match is None:
            raise SystemExit(f"constraints.txt:{number}: {line!r} is not an exact pin")
        found[_normalise(match.group("name"))] = match.group("version")
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write", action="store_true", help="rewrite constraints.txt from pyproject"
    )
    arguments = parser.parse_args()

    pins = declared()
    if arguments.write:
        lines = [
            "# Generated by scripts/check_pins.py from pyproject.toml.",
            "# CI installs with -c constraints.txt so a build resolves the same way twice.",
            "",
        ]
        lines += [f"{name}=={version}" for name, (version, _) in sorted(pins.items())]
        CONSTRAINTS.write_text("\n".join(lines) + "\n")
        print(f"wrote {len(pins)} pins to {CONSTRAINTS.name}")
        return 0

    lock = locked()
    problems: list[str] = []
    for name, (version, group) in sorted(pins.items()):
        if name not in lock:
            problems.append(f"{name} ({group}) is pinned but not in constraints.txt")
        elif lock[name] != version:
            problems.append(
                f"{name}: pyproject says {version}, constraints.txt says {lock[name]}"
            )
    for name in sorted(set(lock) - set(pins)):
        problems.append(f"{name} is in constraints.txt and nothing needs it")

    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            f"\n{len(problems)} problems, run scripts/check_pins.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"{len(pins)} dependencies, all exact, constraints.txt agrees")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
